-- =====================================================================
-- Prim sistemi: şirkete özel kademeler, günlük ve aylık hak edilen prim (satış tutarı üzerinden)
-- =====================================================================
create table commission_rules (
  id          bigint generated by default as identity primary key,
  company_id  uuid not null references companies(id),
  period      text not null check (period in ('daily', 'monthly')),
  min_amount  numeric(14,2) not null,          -- bu tutar ve üstü
  kind        text not null check (kind in ('fixed', 'percent')),
  value       numeric(12,2) not null,          -- sabit ₺ ya da yüzde
  is_active   boolean not null default true,
  created_at  timestamptz not null default now(),
  unique (company_id, period, min_amount)
);
alter table commission_rules enable row level security;
create policy commission_read on commission_rules for select
  using (company_id = current_company_id() and current_user_role() in ('admin','yonetici'));
create policy commission_write on commission_rules for all
  using (company_id = current_company_id() and current_user_role() = 'admin')
  with check (company_id = current_company_id() and current_user_role() = 'admin');

create trigger trg_log_commission_rules after insert or update or delete on commission_rules
  for each row execute function log_change();

-- Prim tabanı: aktif satışın tutarı, iyzico iadesi düşülmüş
create or replace view v_commission_daily with (security_invoker = true) as
with d as (
  select s.company_id, s.seller_id, s.order_date as day,
         count(*) as sale_count,
         sum(s.amount - coalesce(s.iyzico_refunded, 0)) as total
  from sales s
  where s.is_active and s.seller_id is not null
  group by s.company_id, s.seller_id, s.order_date
)
select d.*, coalesce(r.value, 0) as commission, r.min_amount as tier_min
from d
left join lateral (
  select value, min_amount from commission_rules cr
  where cr.company_id = d.company_id and cr.period = 'daily' and cr.is_active and cr.min_amount <= d.total
  order by cr.min_amount desc limit 1
) r on true;

create or replace view v_commission_monthly with (security_invoker = true) as
with m as (
  select company_id, seller_id, date_trunc('month', day)::date as month,
         sum(sale_count) as sale_count, sum(total) as total,
         sum(commission) as daily_commission,
         count(*) filter (where commission > 0) as daily_bonus_days
  from v_commission_daily
  group by company_id, seller_id, date_trunc('month', day)
)
select m.company_id, m.seller_id, p.full_name as seller_name, p.is_active as seller_active,
       m.month, m.sale_count, m.total, m.daily_commission, m.daily_bonus_days,
       r.kind as tier_kind, r.value as tier_value, r.min_amount as tier_min,
       coalesce(case when r.kind = 'percent' then round(m.total * r.value / 100, 2) else r.value end, 0) as monthly_commission,
       nx.min_amount as next_tier_min,
       case when nx.min_amount is not null then nx.min_amount - m.total end as to_next_tier
from m
join profiles p on p.id = m.seller_id
left join lateral (
  select kind, value, min_amount from commission_rules cr
  where cr.company_id = m.company_id and cr.period = 'monthly' and cr.is_active and cr.min_amount <= m.total
  order by cr.min_amount desc limit 1
) r on true
left join lateral (
  select min_amount from commission_rules cr
  where cr.company_id = m.company_id and cr.period = 'monthly' and cr.is_active and cr.min_amount > m.total
  order by cr.min_amount asc limit 1
) nx on true;

