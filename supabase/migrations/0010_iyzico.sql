-- ---------------------------------------------------------------------
-- Otomatik eşleştirme: tutar + tarih (-3/+1 gün) + taksit; iki yönde de tek aday varsa bağla
-- ---------------------------------------------------------------------
create or replace function iyzico_auto_match(p_company uuid) returns int
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  with src as (
    select id from lookups where company_id = p_company and category = 'sale_source' and lower(label) like '%iyzico%'
  ), cand as (
    select t.id as tid, s.id as sid
    from iyzico_transactions t
    join sales s on s.company_id = t.company_id
    where t.company_id = p_company and t.transaction_type = 'PAYMENT' and t.sale_id is null
      and coalesce(t.transaction_status, 1) in (1, 2)
      and s.is_active and s.iyzico_payment_id is null and s.sale_source_id in (select id from src)
      and (t.price = s.amount or t.paid_price = s.amount)
      and (t.transaction_date at time zone 'Europe/Istanbul')::date between s.order_date - 3 and s.order_date + 1
      and coalesce(nullif(t.installment, 0), 1) = coalesce(nullif(s.installments, 0), 1)
  ), uniq as (
    select c.tid, c.sid from cand c
    where (select count(*) from cand x where x.tid = c.tid) = 1
      and (select count(*) from cand y where y.sid = c.sid) = 1
  ), upd_t as (
    update iyzico_transactions t set sale_id = u.sid, matched_by = 'auto', matched_at = now()
    from uniq u where t.id = u.tid
    returning u.sid, t.payment_id, t.merchant_payout_amount
  )
  update sales s set iyzico_payment_id = ut.payment_id, net_amount = ut.merchant_payout_amount, net_source = 'iyzico'
  from upd_t ut where s.id = ut.sid;
  get diagnostics n = row_count;
  perform iyzico_refresh_refunds(p_company);
  return n;
end $$;

-- İade/iptal toplamlarını satışa yansıt
create or replace function iyzico_refresh_refunds(p_company uuid) returns void
language sql security definer set search_path = public as $$
  update sales s set iyzico_refunded = coalesce(r.total, 0)
  from (
    select s2.id, sum(t.price) as total
    from sales s2 left join iyzico_transactions t
      on t.company_id = s2.company_id and t.payment_id = s2.iyzico_payment_id and t.transaction_type in ('REFUND', 'CANCEL')
    where s2.company_id = p_company and s2.iyzico_payment_id is not null
    group by s2.id
  ) r
  where s.id = r.id and s.iyzico_refunded is distinct from coalesce(r.total, 0);
$$;

-- Elle eşleştirme (datacı/yönetici/admin)
create or replace function iyzico_manual_match(p_transaction bigint, p_sale bigint) returns void
language plpgsql security definer set search_path = public as $$
declare t iyzico_transactions; s sales;
begin
  if current_user_role() not in ('admin','yonetici','dataci') then raise exception 'Yetkiniz yok.'; end if;
  select * into t from iyzico_transactions where id = p_transaction and company_id = current_company_id();
  select * into s from sales where id = p_sale and company_id = current_company_id();
  if t.id is null or s.id is null then raise exception 'Kayıt bulunamadı.'; end if;
  if t.transaction_type <> 'PAYMENT' then raise exception 'Yalnız ödeme işlemleri eşleştirilebilir.'; end if;
  -- Eski bağlantıları çöz
  update iyzico_transactions set sale_id = null, matched_by = null, matched_at = null where sale_id = s.id and id <> t.id;
  if t.sale_id is not null and t.sale_id <> s.id then
    update sales set iyzico_payment_id = null, net_source = 'manual' where id = t.sale_id;
  end if;
  update iyzico_transactions set sale_id = s.id, matched_by = 'manual', matched_at = now() where id = t.id;
  update sales set iyzico_payment_id = t.payment_id, net_amount = t.merchant_payout_amount, net_source = 'iyzico' where id = s.id;
  perform iyzico_refresh_refunds(s.company_id);
end $$;

create or replace function iyzico_unmatch(p_sale bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  if current_user_role() not in ('admin','yonetici','dataci') then raise exception 'Yetkiniz yok.'; end if;
  update iyzico_transactions set sale_id = null, matched_by = null, matched_at = null
   where sale_id = p_sale and company_id = current_company_id();
  update sales set iyzico_payment_id = null, net_source = 'manual', iyzico_refunded = 0
   where id = p_sale and company_id = current_company_id();
end $$;

revoke execute on function iyzico_auto_match(uuid), iyzico_refresh_refunds(uuid) from public, anon, authenticated;
revoke execute on function iyzico_manual_match(bigint, bigint), iyzico_unmatch(bigint) from public, anon;
grant execute on function iyzico_manual_match(bigint, bigint), iyzico_unmatch(bigint) to authenticated;

-- Satış listesi görünümüne iyzico alanlarını ekle
create or replace view v_sale_list with (security_invoker = true) as
select s.id, s.company_id, s.order_date, s.amount, s.net_amount, s.installments, s.payer_name,
       s.customer_id, c.full_name as customer_name, c.phone as customer_phone,
       s.seller_id, p.full_name as seller_name,
       s.sale_source_id, src.label as sale_source,
       s.payment_method_id, pm.label as payment_method,
       s.bank_id, b.label as bank,
       s.data_type_id, dt.label as data_type,
       s.note, s.is_active, s.created_at,
       (select string_agg(pr.name, ', ' order by pr.kind desc, pr.sort_order)
          from sale_products sp join products pr on pr.id = sp.product_id
         where sp.sale_id = s.id) as products,
       s.net_source, s.iyzico_payment_id, s.iyzico_refunded
from sales s
join customers c on c.id = s.customer_id
left join profiles p on p.id = s.seller_id
left join lookups src on src.id = s.sale_source_id
left join lookups pm  on pm.id  = s.payment_method_id
left join lookups b   on b.id   = s.bank_id
left join lookups dt  on dt.id  = s.data_type_id;

grant execute on function iyzico_auto_match(uuid), iyzico_refresh_refunds(uuid) to service_role;
