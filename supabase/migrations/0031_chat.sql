-- =====================================================================
-- CRM İÇİ MESAJLAŞMA
--  * Odalar: dm (birebir), group (grup), announce (duyuru: herkes okur, yalnız admin/yönetici yazar)
--  * Birebir mesajları taraflar ve admin görür; gruplar üyelerine açık. Mesajlar silinmez.
--  * Mesaja data iliştirilebilir (customer_id). Anlık iletim: Supabase Realtime.
-- =====================================================================

create table if not exists chat_rooms (
  id              bigint generated by default as identity primary key,
  company_id      uuid not null references companies(id),
  kind            text not null check (kind in ('dm','group','announce')),
  name            text,
  dm_key          text,                       -- birebir odada iki kullanıcının sıralı id'leri (tekil)
  created_by      uuid references profiles(id),
  created_at      timestamptz not null default now(),
  last_message_at timestamptz,
  unique (company_id, dm_key)
);
create table if not exists chat_members (
  room_id      bigint not null references chat_rooms(id),
  user_id      uuid not null references profiles(id),
  last_read_at timestamptz not null default now(),
  joined_at    timestamptz not null default now(),
  primary key (room_id, user_id)
);
create index if not exists chat_members_user on chat_members (user_id);
create table if not exists chat_messages (
  id          bigint generated by default as identity primary key,
  room_id     bigint not null references chat_rooms(id),
  company_id  uuid not null references companies(id),
  user_id     uuid not null references profiles(id),
  body        text not null check (length(body) between 1 and 4000),
  customer_id bigint references customers(id),
  created_at  timestamptz not null default now()
);
create index if not exists chat_messages_room on chat_messages (room_id, created_at desc);

alter table chat_rooms enable row level security;
alter table chat_members enable row level security;
alter table chat_messages enable row level security;

create or replace function chat_can_read(p_room bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from chat_members m where m.room_id = p_room and m.user_id = auth.uid())
      or exists (select 1 from chat_rooms r where r.id = p_room and r.company_id = current_company_id()
                   and r.kind = 'dm' and current_user_role() = 'admin')
$$;
create or replace function chat_can_write(p_room bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from chat_members m join chat_rooms r on r.id = m.room_id
                  where m.room_id = p_room and m.user_id = auth.uid()
                    and (r.kind <> 'announce' or current_user_role() in ('admin','yonetici')))
$$;
revoke execute on function chat_can_read(bigint) from public, anon;
revoke execute on function chat_can_write(bigint) from public, anon;
grant execute on function chat_can_read(bigint) to authenticated;
grant execute on function chat_can_write(bigint) to authenticated;

create policy chat_rooms_read on chat_rooms for select using (company_id = (select current_company_id()) and chat_can_read(id));
create policy chat_members_read on chat_members for select using (chat_can_read(room_id));
create policy chat_members_update on chat_members for update using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy chat_messages_read on chat_messages for select using (company_id = (select current_company_id()) and chat_can_read(room_id));
create policy chat_messages_insert on chat_messages for insert
  with check (company_id = (select current_company_id()) and user_id = (select auth.uid()) and chat_can_write(room_id));

create or replace function chat_touch_room() returns trigger language plpgsql security definer set search_path = public as $$
begin
  update chat_rooms set last_message_at = new.created_at where id = new.room_id;
  update chat_members set last_read_at = new.created_at where room_id = new.room_id and user_id = new.user_id;
  return new;
end $$;
create or replace trigger trg_chat_touch after insert on chat_messages for each row execute function chat_touch_room();

-- Birebir oda aç / bul
create or replace function chat_dm(p_other uuid) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_me uuid := auth.uid(); v_company uuid := current_company_id(); v_key text; v_room bigint;
begin
  if p_other = v_me then raise exception 'Kendinize mesaj gönderemezsiniz'; end if;
  if not exists (select 1 from profiles where id = p_other and company_id = v_company and is_active) then
    raise exception 'Kullanıcı bulunamadı';
  end if;
  v_key := least(v_me::text, p_other::text) || ':' || greatest(v_me::text, p_other::text);
  select id into v_room from chat_rooms where company_id = v_company and dm_key = v_key;
  if v_room is null then
    insert into chat_rooms (company_id, kind, dm_key, created_by) values (v_company, 'dm', v_key, v_me) returning id into v_room;
    insert into chat_members (room_id, user_id) values (v_room, v_me), (v_room, p_other);
  end if;
  return v_room;
end $$;
revoke execute on function chat_dm(uuid) from public, anon;
grant execute on function chat_dm(uuid) to authenticated;

-- Grup aç (admin/yönetici)
create or replace function chat_group(p_name text, p_members uuid[], p_kind text default 'group') returns bigint
language plpgsql security definer set search_path = public as $$
declare v_room bigint; v_company uuid := current_company_id();
begin
  if current_user_role() not in ('admin','yonetici') then raise exception 'Grubu yalnız admin/yönetici açabilir'; end if;
  if p_kind not in ('group','announce') then raise exception 'Geçersiz tür'; end if;
  insert into chat_rooms (company_id, kind, name, created_by) values (v_company, p_kind, left(trim(p_name), 60), auth.uid()) returning id into v_room;
  insert into chat_members (room_id, user_id)
  select v_room, p.id from profiles p
   where p.company_id = v_company and p.is_active and (p.id = any (p_members) or p.id = auth.uid())
  on conflict do nothing;
  return v_room;
end $$;
revoke execute on function chat_group(text, uuid[], text) from public, anon;
grant execute on function chat_group(text, uuid[], text) to authenticated;

-- Gruba üye ekle/çıkar (admin/yönetici)
create or replace function chat_set_member(p_room bigint, p_user uuid, p_on boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  if current_user_role() not in ('admin','yonetici') then raise exception 'Yetkisiz'; end if;
  if not exists (select 1 from chat_rooms where id = p_room and company_id = current_company_id() and kind <> 'dm') then
    raise exception 'Oda bulunamadı';
  end if;
  if p_on then insert into chat_members (room_id, user_id) values (p_room, p_user) on conflict do nothing;
  else delete from chat_members where room_id = p_room and user_id = p_user; end if;
end $$;
revoke execute on function chat_set_member(bigint, uuid, boolean) from public, anon;
grant execute on function chat_set_member(bigint, uuid, boolean) to authenticated;

-- Odalarım + okunmamış sayıları
create or replace function chat_my_rooms()
returns table (room_id bigint, kind text, title text, other_id uuid, last_message_at timestamptz,
               last_body text, last_user text, unread int, member_count int)
language sql stable security definer set search_path = public as $$
  select r.id, r.kind,
         case when r.kind = 'dm' then (select p.full_name from chat_members m2 join profiles p on p.id = m2.user_id
                                         where m2.room_id = r.id and m2.user_id <> auth.uid() limit 1)
              else r.name end,
         case when r.kind = 'dm' then (select m2.user_id from chat_members m2 where m2.room_id = r.id and m2.user_id <> auth.uid() limit 1) end,
         r.last_message_at,
         (select left(x.body, 80) from chat_messages x where x.room_id = r.id order by x.created_at desc limit 1),
         (select p.full_name from chat_messages x join profiles p on p.id = x.user_id where x.room_id = r.id order by x.created_at desc limit 1),
         (select count(*)::int from chat_messages x where x.room_id = r.id and x.created_at > m.last_read_at and x.user_id <> auth.uid()),
         (select count(*)::int from chat_members m3 where m3.room_id = r.id)
    from chat_members m join chat_rooms r on r.id = m.room_id
   where m.user_id = auth.uid()
   order by coalesce(r.last_message_at, r.created_at) desc
$$;
revoke execute on function chat_my_rooms() from public, anon;
grant execute on function chat_my_rooms() to authenticated;

-- Yeni kullanıcı otomatik olarak duyuru kanallarına eklenir
create or replace function chat_join_announce() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.is_active then
    insert into chat_members (room_id, user_id)
    select r.id, new.id from chat_rooms r where r.company_id = new.company_id and r.kind = 'announce'
    on conflict do nothing;
  end if;
  return new;
end $$;
create or replace trigger trg_chat_join_announce after insert or update of is_active on profiles
  for each row execute function chat_join_announce();

