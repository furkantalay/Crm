create table audit_logs (
  id          bigint generated by default as identity primary key,
  company_id  uuid,
  user_id     uuid,
  action      text not null,          -- INSERT | UPDATE | DELETE
  table_name  text not null,
  row_id      text,
  old_data    jsonb,
  new_data    jsonb,
  created_at  timestamptz not null default now()
);
create index on audit_logs (company_id, created_at desc);

-- =====================================================================
-- YARDIMCI FONKSİYONLAR
-- =====================================================================
create or replace function current_company_id() returns uuid
language sql stable security definer set search_path = public as $$
  select company_id from profiles where id = auth.uid() and is_active
$$;

create or replace function current_user_role() returns user_role
language sql stable security definer set search_path = public as $$
  select role from profiles where id = auth.uid() and is_active
$$;

-- Admin, yönetici, datacı, teknik: şirketin tüm datasını görür. Satışçı: sadece kendine atananı.
create or replace function is_staff() returns boolean
language sql stable set search_path = public as $$
  select coalesce(current_user_role() in ('admin','yonetici','dataci','teknik'), false)
$$;

-- Genel log tetikleyicisi
create or replace function log_change() returns trigger
language plpgsql security definer set search_path = public as $$
declare r jsonb := to_jsonb(coalesce(new, old));
begin
  insert into audit_logs (company_id, user_id, action, table_name, row_id, old_data, new_data)
  values ((r->>'company_id')::uuid, auth.uid(), tg_op, tg_table_name, r->>'id',
          case when tg_op <> 'INSERT' then to_jsonb(old) end,
          case when tg_op <> 'DELETE' then to_jsonb(new) end);
  return coalesce(new, old);
end $$;

do $$
declare t text;
begin
  foreach t in array array['customers','sales','expected_sales','meetings',
                           'satisfaction_calls','ad_clients','profiles','products','lookups']
  loop
    execute format('create trigger trg_log_%1$s after insert or update or delete on %1$s
                    for each row execute function log_change()', t);
  end loop;
end $$;

-- Görüşme eklenince müşterinin son not / durum / işlem zamanını güncelle
create or replace function touch_customer_on_interaction() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update customers
     set last_note      = coalesce(new.note, last_note),
         status_id      = coalesce(new.status_id, status_id),
         last_action_at = new.created_at
   where id = new.customer_id;
  return new;
end $$;

create trigger trg_touch_customer after insert on interactions
  for each row execute function touch_customer_on_interaction();

-- Silmeyi engelle (pasife alma zorunlu)
create or replace function block_delete() returns trigger
language plpgsql set search_path = public as $$
begin
  raise exception 'Kayıtlar silinemez; is_active=false ile pasife alın.';
end $$;

create trigger trg_no_delete_customers before delete on customers
  for each row execute function block_delete();
create trigger trg_no_delete_sales before delete on sales
  for each row execute function block_delete();

