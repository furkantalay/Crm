-- =====================================================================
-- TELEFON GÖRÜŞMELERİ (Android "CRM Arama" uygulamasından)
--  * Uygulama telefonun arama geçmişini ingest_calls() ile yollar.
--  * Gizlilik: yalnız CRM'de kayıtlı numaralarla yapılan görüşmeler ve
--    kayıtlı olmayan numaralardan GELEN aramalar saklanır. Satışçının
--    kayıtlı olmayan numaraları araması (özel görüşmeler) hiç saklanmaz.
-- =====================================================================

create table if not exists call_logs (
  id            bigint generated by default as identity primary key,
  company_id    uuid not null references companies(id),
  user_id       uuid not null references profiles(id),
  call_key      text not null,              -- cihazdaki kayıt anahtarı (tekrar gönderimde çift kayıt olmasın)
  phone         text not null,
  phone_norm    text generated always as (right(regexp_replace(phone, '\D', '', 'g'), 10)) stored,
  direction     text not null check (direction in ('in','out','missed','rejected')),
  started_at    timestamptz not null,
  duration_sec  int not null default 0,
  customer_id   bigint references customers(id),
  created_at    timestamptz not null default now(),
  unique (user_id, call_key)
);
create index if not exists call_logs_company_started on call_logs (company_id, started_at desc);
create index if not exists call_logs_user_started on call_logs (user_id, started_at desc);
create index if not exists call_logs_customer on call_logs (customer_id, started_at desc);
create index if not exists call_logs_phone on call_logs (company_id, phone_norm, started_at desc);

alter table call_logs enable row level security;
-- yönetici/datacı/teknik/admin şirketin tümünü, satışçı yalnız kendi aramalarını görür
create policy call_logs_read on call_logs for select
  using (company_id = current_company_id() and (is_staff() or user_id = auth.uid()));
-- yazma yalnız ingest_calls() üzerinden; silme yok

create table if not exists call_devices (
  user_id        uuid primary key references profiles(id),
  company_id     uuid not null references companies(id),
  device_model   text,
  app_version    text,
  permission_ok  boolean not null default false,
  last_sync_at   timestamptz,
  last_call_at   timestamptz,
  updated_at     timestamptz not null default now()
);
alter table call_devices enable row level security;
create policy call_devices_read on call_devices for select
  using (company_id = current_company_id() and (is_staff() or user_id = auth.uid()));

-- Uygulamadan gelen arama listesi
-- p_calls: [{key, phone, dir, at (ISO), dur}]
create or replace function ingest_calls(p_calls jsonb, p_device jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_company uuid;
  v_active boolean;
  c jsonb;
  v_phone text; v_norm text; v_dir text; v_at timestamptz; v_dur int; v_cust bigint;
  n_saved int := 0; n_skipped int := 0; v_max timestamptz;
begin
  if v_uid is null then raise exception 'Giriş gerekli'; end if;
  select company_id, is_active into v_company, v_active from profiles where id = v_uid;
  if v_company is null or not v_active then raise exception 'Kullanıcı pasif'; end if;

  for c in select * from jsonb_array_elements(coalesce(p_calls, '[]'::jsonb)) loop
    v_phone := left(coalesce(c->>'phone', ''), 40);
    v_norm  := right(regexp_replace(v_phone, '\D', '', 'g'), 10);
    v_dir   := c->>'dir';
    v_at    := (c->>'at')::timestamptz;
    v_dur   := greatest(coalesce((c->>'dur')::int, 0), 0);
    if length(v_norm) < 10 or v_dir not in ('in','out','missed','rejected') or v_at is null
       or v_at > now() + interval '1 day' or v_at < now() - interval '60 days' then
      n_skipped := n_skipped + 1; continue;
    end if;

    -- önce kişinin kendi datası, sonra şirketteki herhangi bir aktif data
    select cu.id into v_cust from customers cu
     where cu.company_id = v_company and cu.phone_norm = v_norm
     order by (cu.assigned_to = v_uid) desc nulls last, cu.is_active desc, cu.applied_at desc nulls last
     limit 1;

    -- gizlilik: CRM'de olmayan numaraya yapılan giden arama saklanmaz
    if v_cust is null and v_dir = 'out' then
      n_skipped := n_skipped + 1; continue;
    end if;

    insert into call_logs (company_id, user_id, call_key, phone, direction, started_at, duration_sec, customer_id)
    values (v_company, v_uid, left(c->>'key', 120), v_phone, v_dir, v_at, v_dur, v_cust)
    on conflict (user_id, call_key) do nothing;
    if found then
      n_saved := n_saved + 1;
      v_max := greatest(v_max, v_at);
      -- görüşülen datanın "son işlem" zamanını güncelle
      if v_cust is not null and v_dur > 0 then
        update customers set last_action_at = greatest(coalesce(last_action_at, v_at), v_at) where id = v_cust;
      end if;
    end if;
  end loop;

  insert into call_devices (user_id, company_id, device_model, app_version, permission_ok, last_sync_at, last_call_at, updated_at)
  values (v_uid, v_company, left(p_device->>'model', 80), left(p_device->>'version', 20),
          coalesce((p_device->>'permission_ok')::boolean, true), now(), v_max, now())
  on conflict (user_id) do update set
    device_model = coalesce(excluded.device_model, call_devices.device_model),
    app_version  = coalesce(excluded.app_version, call_devices.app_version),
    permission_ok = excluded.permission_ok,
    last_sync_at = now(),
    last_call_at = greatest(call_devices.last_call_at, excluded.last_call_at),
    updated_at = now();

  return jsonb_build_object('saved', n_saved, 'skipped', n_skipped);
end $$;
revoke execute on function ingest_calls(jsonb, jsonb) from public, anon;
grant execute on function ingest_calls(jsonb, jsonb) to authenticated;

-- Liste görünümü (RLS'i çağıranın yetkisiyle uygular)
create or replace view v_call_list with (security_invoker = true) as
select cl.id, cl.company_id, cl.user_id, p.full_name as user_name, cl.phone, cl.phone_norm, cl.direction,
       cl.started_at, cl.duration_sec, cl.customer_id, cu.full_name as customer_name,
       -- bu aramadan sonra aynı numarayla şirketten biri konuştu mu / geri arandı mı
       exists (select 1 from call_logs x
                where x.company_id = cl.company_id and x.phone_norm = cl.phone_norm
                  and x.started_at > cl.started_at
                  and (x.direction = 'out' or (x.direction = 'in' and x.duration_sec > 0))) as followed_up
  from call_logs cl
  join profiles p on p.id = cl.user_id
  left join customers cu on cu.id = cl.customer_id;

-- Ekip Durumu'na aramaları ekle: aramalar da "iş" sayılır
create or replace function work_events(p_company uuid, p_from timestamptz, p_to timestamptz)
returns table (user_id uuid, at timestamptz, kind text, detail text)
language sql stable security definer set search_path = public as $$
  select i.user_id, i.created_at,
         case when i.channel = 'Excel' then 'Toplu aktarım' else 'Not' end,
         coalesce(c.full_name, '') || coalesce(' · ' || nullif(i.channel,''), '') ||
           coalesce(' · ' || left(i.note, 90), '')
    from interactions i left join customers c on c.id = i.customer_id
   where i.company_id = p_company and i.created_at >= p_from and i.created_at < p_to and i.user_id is not null
  union all
  select s.created_by, s.created_at, 'Satış',
         coalesce(c.full_name, '') || ' · ' || to_char(s.amount, 'FM999G999G990') || ' ₺'
    from sales s left join customers c on c.id = s.customer_id
   where s.company_id = p_company and s.created_at >= p_from and s.created_at < p_to and s.created_by is not null
  union all
  select cl.user_id, cl.started_at,
         case cl.direction when 'out' then 'Arama (giden)' when 'in' then 'Arama (gelen)'
                           when 'missed' then 'Cevapsız arama' else 'Reddedilen arama' end,
         coalesce(cu.full_name, cl.phone) ||
           case when cl.duration_sec > 0 then ' · ' || (cl.duration_sec / 60) || ' dk ' || (cl.duration_sec % 60) || ' sn'
                when cl.direction = 'out' then ' · açılmadı' else '' end
    from call_logs cl left join customers cu on cu.id = cl.customer_id
   where cl.company_id = p_company and cl.started_at >= p_from and cl.started_at < p_to
     and cl.direction in ('out','in')   -- cevapsız/reddedilen kişinin yaptığı bir iş değil
  union all
  select a.user_id, a.created_at,
         case
           when a.table_name = 'customers'          and a.action = 'INSERT' then 'Data ekledi'
           when a.table_name = 'customers'                                   then 'Data güncelledi'
           when a.table_name = 'sales'                                       then 'Satış güncelledi'
           when a.table_name = 'expected_sales'                              then 'Beklenen satış'
           when a.table_name = 'meetings'                                    then 'Toplantı'
           when a.table_name = 'satisfaction_calls'                          then 'Memnuniyet araması'
           when a.table_name = 'ad_clients'                                  then 'Reklam müşterisi'
           else a.table_name
         end,
         coalesce(a.new_data->>'full_name', a.new_data->>'note', a.new_data->>'title', '')
    from audit_logs a
   where a.company_id = p_company and a.created_at >= p_from and a.created_at < p_to
     and a.user_id is not null
     and a.table_name in ('customers','sales','expected_sales','meetings','satisfaction_calls','ad_clients')
     and not (a.table_name = 'sales' and a.action = 'INSERT')
     and not (a.table_name = 'customers' and a.action = 'UPDATE'
              and (a.new_data - array['last_note','status_id','last_action_at','applied_at'])
                = (a.old_data - array['last_note','status_id','last_action_at','applied_at']))
$$;
revoke execute on function work_events(uuid, timestamptz, timestamptz) from public, anon, authenticated;

-- team_activity: arama sayıları ve uygulama durumu eklendi
drop function if exists team_activity(date);
create function team_activity(p_day date)
returns table (
  user_id uuid, full_name text, role user_role, last_seen_at timestamptz,
  first_at timestamptz, last_event_at timestamptz, last_event_kind text, last_event_detail text,
  last_ping_at timestamptz, last_ping_active boolean, last_active_at timestamptz,
  note_count int, sale_count int, sale_amount numeric, other_count int,
  active_minutes int, open_minutes int, longest_gap_minutes int, longest_gap_from timestamptz,
  call_out int, call_answered int, call_in int, call_missed int, talk_seconds int,
  app_last_sync timestamptz, app_permission_ok boolean
)
language plpgsql stable security definer set search_path = public as $$
declare
  v_company uuid := current_company_id();
  v_from timestamptz := (p_day::timestamp) at time zone 'Europe/Istanbul';
  v_to   timestamptz := ((p_day + 1)::timestamp) at time zone 'Europe/Istanbul';
  v_now  timestamptz := least(now(), ((p_day + 1)::timestamp) at time zone 'Europe/Istanbul');
begin
  if current_user_role() not in ('admin','yonetici') then
    raise exception 'Bu ekrana yalnız admin ve yöneticiler erişebilir';
  end if;
  return query
  with ev as (select * from work_events(v_company, v_from, v_to)),
  pg as (select * from presence_pings p where p.company_id = v_company and p.at >= v_from and p.at < v_to),
  cl as (select * from call_logs c where c.company_id = v_company and c.started_at >= v_from and c.started_at < v_to),
  gaps as (
    select e.user_id, e.at as gap_from,
           coalesce(lead(e.at) over (partition by e.user_id order by e.at),
                    case when exists (select 1 from pg where pg.user_id = e.user_id and pg.at > v_now - interval '3 minutes')
                         then v_now end) - e.at as gap
      from ev e
  ),
  lg as (
    select distinct on (g.user_id) g.user_id, g.gap, g.gap_from
      from gaps g where g.gap is not null order by g.user_id, g.gap desc
  )
  select p.id, p.full_name, p.role, p.last_seen_at,
         least((select min(e.at) from ev e where e.user_id = p.id),
               (select min(x.at) from pg x where x.user_id = p.id and x.active)),
         le.at, le.kind, le.detail,
         lp.at, lp.active,
         (select max(x.at) from pg x where x.user_id = p.id and x.active),
         (select count(*)::int from ev e where e.user_id = p.id and e.kind = 'Not'),
         (select count(*)::int from ev e where e.user_id = p.id and e.kind = 'Satış'),
         coalesce((select sum(s.amount) from sales s where s.company_id = v_company and s.created_by = p.id
                     and s.created_at >= v_from and s.created_at < v_to and s.is_active), 0),
         (select count(*)::int from ev e where e.user_id = p.id and e.kind not in ('Not','Satış') and e.kind not like 'Arama%'),
         (select count(*)::int from pg x where x.user_id = p.id and x.active),
         (select count(*)::int from pg x where x.user_id = p.id),
         (extract(epoch from lg.gap) / 60)::int, lg.gap_from,
         (select count(*)::int from cl c where c.user_id = p.id and c.direction = 'out'),
         (select count(*)::int from cl c where c.user_id = p.id and c.direction = 'out' and c.duration_sec > 0),
         (select count(*)::int from cl c where c.user_id = p.id and c.direction = 'in'),
         (select count(*)::int from cl c where c.user_id = p.id and c.direction in ('missed','rejected')),
         coalesce((select sum(c.duration_sec)::int from cl c where c.user_id = p.id), 0),
         d.last_sync_at, d.permission_ok
    from profiles p
    left join lateral (select e.at, e.kind, e.detail from ev e where e.user_id = p.id order by e.at desc limit 1) le on true
    left join lateral (select x.at, x.active from pg x where x.user_id = p.id order by x.at desc limit 1) lp on true
    left join lg on lg.user_id = p.id
    left join call_devices d on d.user_id = p.id
   where p.company_id = v_company and p.is_active and p.role <> 'admin'
   order by p.role, p.full_name;
end $$;
revoke execute on function team_activity(date) from public, anon;
grant execute on function team_activity(date) to authenticated;
