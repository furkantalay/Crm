-- Şirket kendi kaydını görür, sadece admin günceller
create policy company_read  on companies for select using (id = current_company_id());
create policy company_admin on companies for update using (id = current_company_id() and current_user_role() = 'admin');

-- Profiller: şirket içi herkes listeyi görür; admin/yönetici yönetir
create policy profiles_read  on profiles for select using (company_id = current_company_id());
create policy profiles_write on profiles for all
  using (company_id = current_company_id() and current_user_role() in ('admin','yonetici'))
  with check (company_id = current_company_id() and current_user_role() in ('admin','yonetici'));

-- Ayar listeleri ve ürünler: herkes okur, admin/yönetici yazar
create policy lookups_read  on lookups  for select using (company_id = current_company_id());
create policy lookups_write on lookups  for all
  using (company_id = current_company_id() and current_user_role() in ('admin','yonetici'))
  with check (company_id = current_company_id() and current_user_role() in ('admin','yonetici'));
create policy products_read  on products for select using (company_id = current_company_id());
create policy products_write on products for all
  using (company_id = current_company_id() and current_user_role() in ('admin','yonetici'))
  with check (company_id = current_company_id() and current_user_role() in ('admin','yonetici'));

-- Datalar: staff hepsini, satışçı kendine atananı görür/günceller; ekleme staff
create policy customers_read on customers for select
  using (company_id = current_company_id() and (is_staff() or assigned_to = auth.uid()));
create policy customers_insert on customers for insert
  with check (company_id = current_company_id() and is_staff());
create policy customers_update on customers for update
  using (company_id = current_company_id() and (is_staff() or assigned_to = auth.uid()))
  with check (company_id = current_company_id() and (is_staff() or assigned_to = auth.uid()));

-- Görüşmeler: müşteriyi görebilen görüşmeyi görür/ekler
create policy interactions_read on interactions for select
  using (company_id = current_company_id()
         and exists (select 1 from customers c where c.id = customer_id));
create policy interactions_insert on interactions for insert
  with check (company_id = current_company_id() and user_id = auth.uid()
              and exists (select 1 from customers c where c.id = customer_id));

-- Satışlar: staff hepsini, satışçı kendi satışlarını
create policy sales_read on sales for select
  using (company_id = current_company_id() and (is_staff() or seller_id = auth.uid()));
create policy sales_write on sales for insert
  with check (company_id = current_company_id() and (is_staff() or seller_id = auth.uid()));
create policy sales_update on sales for update
  using (company_id = current_company_id() and (is_staff() or seller_id = auth.uid()))
  with check (company_id = current_company_id() and (is_staff() or seller_id = auth.uid()));

create policy sale_products_all on sale_products for all
  using (exists (select 1 from sales s where s.id = sale_id))
  with check (exists (select 1 from sales s where s.id = sale_id));

-- Beklenen satış, toplantı: staff hepsi, satışçı kendininki
create policy expected_all on expected_sales for all
  using (company_id = current_company_id() and (is_staff() or seller_id = auth.uid()))
  with check (company_id = current_company_id() and (is_staff() or seller_id = auth.uid()));
create policy meetings_all on meetings for all
  using (company_id = current_company_id() and (is_staff() or seller_id = auth.uid()))
  with check (company_id = current_company_id() and (is_staff() or seller_id = auth.uid()));

-- Memnuniyet: staff hepsi, satışçı sorumlu olduğu aramalar
create policy satisfaction_all on satisfaction_calls for all
  using (company_id = current_company_id() and (is_staff() or responsible_id = auth.uid()))
  with check (company_id = current_company_id() and (is_staff() or responsible_id = auth.uid()));

-- Reklam yönetimi: genel kayıtlar admin/yönetici/datacı; özel kayıtlar sadece admin
create policy ad_clients_all on ad_clients for all
  using (company_id = current_company_id()
         and ((not is_admin_private and current_user_role() in ('admin','yonetici','dataci'))
              or current_user_role() = 'admin'))
  with check (company_id = current_company_id()
         and ((not is_admin_private and current_user_role() in ('admin','yonetici','dataci'))
              or current_user_role() = 'admin'));

-- Duyurular: herkes okur, staff yazar
create policy ann_read  on announcements for select using (company_id = current_company_id());
create policy ann_write on announcements for all
  using (company_id = current_company_id() and is_staff())
  with check (company_id = current_company_id() and is_staff());

-- Bildirimler: kişi kendi bildirimini görür / okundu işaretler
create policy notif_own on notifications for all
  using (user_id = auth.uid()) with check (user_id = auth.uid());

-- Loglar: sadece admin ve teknik okur (yazma tetikleyiciden)
create policy logs_read on audit_logs for select
  using (company_id = current_company_id() and current_user_role() in ('admin','teknik'));

