-- =====================================================================
-- ASİSTAN + GÖREVLER
--  * Furkan (veya yönetici) asistana yazar/söyler → yapay zekâ görevlere böler
--  * Görev bir çalışana verildiyse ona bildirim gider; iş bitene kadar hatırlatılır
--  * Tamamlanınca görevi veren kişiye "✅ tamamlandı" bildirimi gider
-- =====================================================================
create table if not exists tasks (
  id               bigint generated by default as identity primary key,
  company_id       uuid not null references companies(id),
  created_by       uuid not null references profiles(id),
  assignee         uuid references profiles(id),          -- null = kendime not / iş
  title            text not null,
  details          text,
  due_at           timestamptz,
  status           text not null default 'acik' check (status in ('acik', 'yapildi', 'iptal')),
  done_at          timestamptz,
  done_note        text,
  customer_id      bigint references customers(id),
  source           text not null default 'elle',          -- elle | asistan
  last_reminded_at timestamptz,
  remind_count     int not null default 0,
  boss_warned_at   timestamptz,
  created_at       timestamptz not null default now()
);
create index if not exists tasks_assignee_open on tasks (assignee, status, due_at);
create index if not exists tasks_creator on tasks (created_by, status);
alter table tasks enable row level security;

create policy tasks_read on tasks for select to authenticated using (
  company_id = (select current_company_id())
  and (created_by = (select auth.uid()) or assignee = (select auth.uid())
       or (select current_user_role()) in ('admin', 'yonetici')));
create policy tasks_insert on tasks for insert to authenticated with check (
  company_id = (select current_company_id()) and created_by = (select auth.uid()));
create policy tasks_update on tasks for update to authenticated using (
  company_id = (select current_company_id())
  and (created_by = (select auth.uid()) or assignee = (select auth.uid())
       or (select current_user_role()) = 'admin'));

-- Yeni görev bir başkasına verildiyse bildir
create or replace function tasks_notify_new() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.assignee is not null and new.assignee <> new.created_by then
    insert into notifications (company_id, user_id, customer_id, title, body, link)
    select new.company_id, new.assignee, new.customer_id, '📌 Yeni görev: ' || new.title,
           concat_ws(' · ', 'Veren: ' || p.full_name,
                     case when new.due_at is not null then 'Son: ' || to_char(new.due_at at time zone 'Europe/Istanbul', 'DD.MM HH24:MI') end,
                     new.details),
           '/gorevler'
      from profiles p where p.id = new.created_by;
  end if;
  return new;
end $$;
create or replace trigger trg_tasks_notify_new after insert on tasks for each row execute function tasks_notify_new();

-- Tamamla / geri al (görevi alan, veren veya admin)
create or replace function task_set_status(p_id bigint, p_status text, p_note text default null) returns void
language plpgsql security definer set search_path = public as $$
declare t tasks%rowtype; me uuid := auth.uid(); v_name text;
begin
  select * into t from tasks where id = p_id and company_id = current_company_id();
  if not found then raise exception 'Görev bulunamadı'; end if;
  if not (t.created_by = me or t.assignee = me or current_user_role() = 'admin') then raise exception 'Yetkisiz'; end if;
  if p_status not in ('acik', 'yapildi', 'iptal') then raise exception 'Geçersiz durum'; end if;
  update tasks set status = p_status,
         done_at = case when p_status = 'yapildi' then now() end,
         done_note = case when p_status = 'yapildi' then nullif(trim(p_note), '') else done_note end
   where id = p_id;
  -- görevi veren başkasıysa haber ver
  if p_status = 'yapildi' and t.created_by <> me then
    select full_name into v_name from profiles where id = me;
    insert into notifications (company_id, user_id, customer_id, title, body, link)
    values (t.company_id, t.created_by, t.customer_id, '✅ ' || v_name || ' tamamladı: ' || t.title,
            nullif(trim(p_note), ''), '/asistan');
  end if;
end $$;
revoke execute on function task_set_status(bigint, text, text) from public, anon;
grant execute on function task_set_status(bigint, text, text) to authenticated;

-- Hatırlatmalar (15 dk'da bir; mesai saatlerinde)
--  * süresi gelen/geçen açık görev → görevliye (yoksa sahibine) en fazla 3 saatte bir
--  * tarihsiz açık görev → her mesai sabahı bir kez
--  * 1 günden fazla geciken başkasına verilmiş görev → veren kişiye günde bir uyarı
create or replace function task_reminders() returns int
language plpgsql security definer set search_path = public as $$
declare t record; n int := 0; v_now timestamp := now() at time zone 'Europe/Istanbul';
  v_today_start timestamptz; s jsonb;
begin
  for t in
    select k.*, c.settings, coalesce(k.assignee, k.created_by) as who, pa.full_name as who_name
      from tasks k join companies c on c.id = k.company_id
      join profiles pa on pa.id = coalesce(k.assignee, k.created_by)
     where k.status = 'acik' and pa.is_active
  loop
    s := coalesce(t.settings->'speed', '{}'::jsonb);
    continue when not (extract(isodow from v_now)::int = any(coalesce(
                         (select array_agg(x::int) from jsonb_array_elements_text(s->'days') x), array[1,2,3,4,5,6])))
              or v_now::time < coalesce(s->>'start', '09:00')::time
              or v_now::time > coalesce(s->>'end', '19:00')::time;
    v_today_start := (v_now::date + coalesce(s->>'start', '09:00')::time) at time zone 'Europe/Istanbul';

    if t.due_at is not null and t.due_at <= now() then
      if t.last_reminded_at is null or t.last_reminded_at < now() - interval '3 hours' then
        insert into notifications (company_id, user_id, customer_id, title, body, link)
        values (t.company_id, t.who, t.customer_id,
                case when t.due_at < now() - interval '1 hour' then '⏰ Gecikti: ' else '⏰ Zamanı geldi: ' end || t.title,
                'Son tarih: ' || to_char(t.due_at at time zone 'Europe/Istanbul', 'DD.MM HH24:MI'),
                case when t.assignee is null or t.assignee = t.created_by then '/asistan' else '/gorevler' end);
        update tasks set last_reminded_at = now(), remind_count = remind_count + 1 where id = t.id;
        n := n + 1;
      end if;
      if t.assignee is not null and t.assignee <> t.created_by and t.due_at < now() - interval '1 day'
         and (t.boss_warned_at is null or t.boss_warned_at < now() - interval '1 day') then
        insert into notifications (company_id, user_id, customer_id, title, body, link)
        values (t.company_id, t.created_by, t.customer_id, '⚠️ ' || t.who_name || ' geciktirdi: ' || t.title,
                (now()::date - t.due_at::date) || ' gündür bekliyor, ' || t.remind_count || ' kez hatırlatıldı', '/asistan');
        update tasks set boss_warned_at = now() where id = t.id;
      end if;
    elsif t.due_at is null and (t.last_reminded_at is null or t.last_reminded_at < v_today_start)
          and t.created_at < v_today_start then
      insert into notifications (company_id, user_id, customer_id, title, body, link)
      values (t.company_id, t.who, t.customer_id, '📌 Açık işin var: ' || t.title, t.details,
              case when t.assignee is null or t.assignee = t.created_by then '/asistan' else '/gorevler' end);
      update tasks set last_reminded_at = now(), remind_count = remind_count + 1 where id = t.id;
      n := n + 1;
    end if;
  end loop;
  return n;
end $$;
revoke execute on function task_reminders() from public, anon, authenticated;
select cron.schedule('task-reminders', '*/15 * * * *', $$select public.task_reminders()$$);
