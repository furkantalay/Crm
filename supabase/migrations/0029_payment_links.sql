create table if not exists payment_links (
  id            bigint generated by default as identity primary key,
  company_id    uuid not null references companies(id),
  customer_id   bigint not null references customers(id),
  seller_id     uuid not null references profiles(id),
  product_ids   uuid[] not null default '{}',
  description   text,
  amount        numeric(12,2) not null check (amount > 0),
  token         text unique,
  url           text,
  status        text not null default 'bekliyor' check (status in ('bekliyor','odendi','iptal','hata')),
  sale_id       bigint references sales(id),
  error         text,
  created_by    uuid references profiles(id),
  created_at    timestamptz not null default now(),
  paid_at       timestamptz,
  checked_at    timestamptz
);
create index if not exists payment_links_pending on payment_links (company_id, status, created_at desc);
create index if not exists payment_links_customer on payment_links (customer_id, created_at desc);
alter table payment_links enable row level security;
create policy payment_links_read on payment_links for select
  using (company_id = (select current_company_id()) and ((select is_staff()) or seller_id = (select auth.uid())));
-- yazma yalnız iyzico-link fonksiyonu (service role) üzerinden

insert into sync_control (name) values ('iyzico_links') on conflict do nothing;

-- Ödeme geldi: satışı gir (yalnız service role)
create or replace function payment_link_paid(p_link bigint, p_installments int default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare l payment_links%rowtype; v_sale bigint; v_src uuid; v_pm uuid; v_type uuid; v_cname text;
begin
  select * into l from payment_links where id = p_link for update;
  if not found or l.status <> 'bekliyor' then return l.sale_id; end if;
  select id into v_src from lookups where company_id = l.company_id and category = 'sale_source' and label ilike 'iyzico' limit 1;
  select id into v_pm from lookups where company_id = l.company_id and category = 'payment_method'
     and label = case when coalesce(p_installments, 1) > 1 then 'Taksitli' else 'Tek Çekim' end limit 1;
  select data_type_id, full_name into v_type, v_cname from customers where id = l.customer_id;

  insert into sales (company_id, customer_id, seller_id, order_date, amount, net_amount, sale_source_id, payment_method_id,
                     installments, data_type_id, note, created_by, extra)
  values (l.company_id, l.customer_id, l.seller_id, (now() at time zone 'Europe/Istanbul')::date, l.amount, l.amount,
          v_src, v_pm, p_installments, v_type, coalesce(l.description, 'iyzico ödeme bağlantısı'), l.seller_id,
          jsonb_build_object('payment_link', l.id))
  returning id into v_sale;
  insert into sale_products (sale_id, product_id) select v_sale, unnest(l.product_ids);

  update payment_links set status = 'odendi', paid_at = now(), sale_id = v_sale where id = l.id;

  insert into notifications (company_id, user_id, customer_id, title, body, link)
  select l.company_id, u.id, l.customer_id, '💳 Ödeme geldi: ' || v_cname,
         to_char(l.amount, 'FM999G999G990') || ' ₺ · satış otomatik girildi', '/datalar/' || l.customer_id
    from profiles u
   where u.company_id = l.company_id and u.is_active and (u.id = l.seller_id or u.role in ('admin','yonetici'));
  return v_sale;
end $$;
revoke execute on function payment_link_paid(bigint, int) from public, anon, authenticated;
grant execute on function payment_link_paid(bigint, int) to service_role;

