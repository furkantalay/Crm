create table iyzico_transactions (
  id                      bigint generated by default as identity primary key,
  company_id              uuid not null references companies(id),
  transaction_id          text not null,
  transaction_type        text not null,               -- PAYMENT | REFUND | CANCEL
  transaction_date        timestamptz not null,
  payment_id              text,
  payment_tx_id           text,
  price                   numeric(12,2),
  paid_price              numeric(12,2),
  merchant_payout_amount  numeric(12,2),
  iyzico_commission       numeric(12,2),
  iyzico_fee              numeric(12,2),
  installment             int,
  transaction_status      int,                         -- 1/2 onaylı, 0 fraud incelemesi, -1 red
  raw                     jsonb not null default '{}',
  sale_id                 bigint references sales(id),
  matched_by              text,                        -- auto | manual
  matched_at              timestamptz,
  synced_at               timestamptz not null default now(),
  unique (company_id, transaction_id)
);
create index on iyzico_transactions (company_id, transaction_date desc);
create index on iyzico_transactions (company_id, payment_id);
create index on iyzico_transactions (sale_id);

alter table sales add column iyzico_payment_id text;
alter table sales add column net_source text not null default 'manual';   -- manual | iyzico
alter table sales add column iyzico_refunded numeric(12,2) not null default 0;
create index on sales (company_id, iyzico_payment_id);

alter table iyzico_transactions enable row level security;
create policy iyzico_read on iyzico_transactions for select
  using (company_id = current_company_id() and current_user_role() in ('admin','yonetici','dataci','teknik'));
create policy iyzico_update on iyzico_transactions for update
  using (company_id = current_company_id() and current_user_role() in ('admin','yonetici','dataci'))
  with check (company_id = current_company_id() and current_user_role() in ('admin','yonetici','dataci'));

