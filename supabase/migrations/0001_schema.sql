-- =====================================================================
--  CRM — çok şirketli (multi-tenant) veritabanı şeması
--  Hedef: Supabase (PostgreSQL 15+)
--  Kural: Kayıtlar fiziksel olarak silinmez; is_active=false ile pasife alınır.
--         Her tablo company_id taşır, RLS ile şirketler birbirini göremez.
-- =====================================================================

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------
-- 1. ŞİRKETLER (tenant) ve KULLANICILAR
-- ---------------------------------------------------------------------
create table companies (
  id                     uuid primary key default gen_random_uuid(),
  name                   text not null,
  slug                   text not null unique,              -- crm.alanadi.com/<slug> veya alt alan
  logo_url               text,
  brand_color            text default '#0f172a',
  default_logout_minutes int  not null default 30,          -- genel hareketsizlik süresi
  plan                   text not null default 'trial',     -- trial | basic | pro
  settings               jsonb not null default '{}',
  is_active              boolean not null default true,
  created_at             timestamptz not null default now()
);

create type user_role as enum ('admin', 'yonetici', 'dataci', 'satisci', 'teknik');

create table profiles (
  id                  uuid primary key references auth.users(id) on delete cascade,
  company_id          uuid not null references companies(id),
  full_name           text not null,                  -- ekranda görünen ad (İREM, ZEYNEP…)
  username            text not null,
  role                user_role not null default 'satisci',
  is_active           boolean not null default true,
  auto_logout_enabled boolean not null default false,
  auto_logout_minutes int,                            -- boşsa şirketin genel süresi
  last_seen_at        timestamptz,
  created_by          uuid references profiles(id),
  created_at          timestamptz not null default now(),
  unique (company_id, username)
);
create index on profiles (company_id);

-- ---------------------------------------------------------------------
-- 2. ŞİRKETE ÖZEL AYARLANABİLİR LİSTELER
--    (data tipi, görüşme durumu, satış kaynağı, ödeme yöntemi, banka, sektör)
-- ---------------------------------------------------------------------
create type lookup_category as enum
  ('data_type', 'contact_status', 'sale_source', 'payment_method', 'bank', 'sector');

create table lookups (
  id          uuid primary key default gen_random_uuid(),
  company_id  uuid not null references companies(id),
  category    lookup_category not null,
  label       text not null,
  color       text,
  is_won      boolean not null default false,   -- contact_status: "Satış" durumu mu?
  sort_order  int not null default 0,
  is_active   boolean not null default true,
  unique (company_id, category, label)
);
create index on lookups (company_id, category);

-- Ürün / paket (sizde: eğitimler)
create table products (
  id          uuid primary key default gen_random_uuid(),
  company_id  uuid not null references companies(id),
  name        text not null,
  kind        text not null default 'program',  -- program (eğitim) | package (paket)
  includes    text[],                            -- paketin içerdiği programlar
  list_price  numeric(12,2),
  is_active   boolean not null default true,
  sort_order  int not null default 0,
  created_at  timestamptz not null default now(),
  unique (company_id, kind, name)
);

-- ---------------------------------------------------------------------
-- 3. DATALAR (müşteri adayları)
-- ---------------------------------------------------------------------
create table customers (
  id              bigint generated by default as identity primary key,
  company_id      uuid not null references companies(id),
  legacy_id       bigint,                                  -- eski CRM'deki ID
  full_name       text not null,
  phone           text not null,
  email           text,
  city            text,
  phone_norm      text generated always as (right(regexp_replace(phone, '\D', '', 'g'), 10)) stored,
  sector          text,
  data_type_id    uuid references lookups(id),
  status_id       uuid references lookups(id),
  assigned_to     uuid references profiles(id),            -- satışçı
  assigned_by     uuid references profiles(id),            -- atayan (datacı)
  last_note       text,                                    -- son görüşme notu (hızlı liste için)
  applied_at      timestamptz,                             -- son başvuru tarihi
  last_action_at  timestamptz,
  extra           jsonb not null default '{}',             -- form cevapları vb.
  is_active       boolean not null default true,
  deactivated_at  timestamptz,
  deactivated_by  uuid references profiles(id),
  created_at      timestamptz not null default now(),
  unique (company_id, legacy_id)
);
create index on customers (company_id, assigned_to, is_active);
create index on customers (company_id, phone_norm);
create index on customers (company_id, applied_at desc);
create index on customers (company_id, last_action_at desc);

-- Görüşme geçmişi (her not/arama bir satır)
create table interactions (
  id           bigint generated by default as identity primary key,
  company_id   uuid not null references companies(id),
  customer_id  bigint not null references customers(id),
  user_id      uuid references profiles(id),
  status_id    uuid references lookups(id),
  channel      text,                    -- Telefon, WhatsApp, Excel, Memnuniyet…
  note         text,
  next_followup_at timestamptz,
  created_at   timestamptz not null default now()
);
create index on interactions (customer_id, created_at desc);

-- ---------------------------------------------------------------------
-- 4. SATIŞLAR
-- ---------------------------------------------------------------------
create table sales (
  id                 bigint generated by default as identity primary key,
  company_id         uuid not null references companies(id),
  legacy_id          bigint,
  customer_id        bigint not null references customers(id),
  seller_id          uuid references profiles(id),
  order_date         date not null default current_date,
  amount             numeric(12,2) not null,           -- Tutar
  net_amount         numeric(12,2),                    -- Bize Gelen (komisyon/kesinti sonrası)
  payer_name         text,                             -- Ödeyen
  bank_id            uuid references lookups(id),
  sale_source_id     uuid references lookups(id),      -- iyzico, Havale/EFT…
  payment_method_id  uuid references lookups(id),      -- Tek çekim, Taksitli…
  installments       int,
  data_type_id       uuid references lookups(id),
  sector             text,
  call_date          date,
  note               text,
  extra              jsonb not null default '{}',
  is_active          boolean not null default true,
  created_by         uuid references profiles(id),
  created_at         timestamptz not null default now(),
  unique (company_id, legacy_id)
);
create index on sales (company_id, order_date desc);
create index on sales (company_id, seller_id, order_date);

create table sale_products (
  sale_id     bigint not null references sales(id) on delete cascade,
  product_id  uuid   not null references products(id),
  primary key (sale_id, product_id)
);

-- ---------------------------------------------------------------------
-- 5. BEKLENEN SATIŞLAR, TOPLANTILAR, MEMNUNİYET
-- ---------------------------------------------------------------------
create type expected_status as enum ('bekliyor', 'ertelendi', 'vazgecti', 'kazanildi');

create table expected_sales (
  id           bigint generated by default as identity primary key,
  company_id   uuid not null references companies(id),
  customer_id  bigint not null references customers(id),
  seller_id    uuid references profiles(id),
  expected_at  timestamptz,
  amount       numeric(12,2),
  status       expected_status not null default 'bekliyor',
  note         text,
  sale_id      bigint references sales(id),     -- kazanıldıysa bağlı satış
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index on expected_sales (company_id, status);

create type meeting_status as enum ('planlandi', 'yapildi', 'ertelendi', 'iptal');

create table meetings (
  id            bigint generated by default as identity primary key,
  company_id    uuid not null references companies(id),
  customer_id   bigint not null references customers(id),
  seller_id     uuid references profiles(id),
  title         text,
  scheduled_at  timestamptz not null,
  status        meeting_status not null default 'planlandi',
  note          text,
  created_by    uuid references profiles(id),
  created_at    timestamptz not null default now()
);
create index on meetings (company_id, scheduled_at);

create type satisfaction_status as enum ('bekliyor', 'arandi', 'ulasilamadi', 'memnun', 'sikayet_var');

create table satisfaction_calls (
  id              bigint generated by default as identity primary key,
  company_id      uuid not null references companies(id),
  customer_id     bigint not null references customers(id),
  sale_id         bigint references sales(id),
  sold_by         uuid references profiles(id),       -- satışı yapan (değişmez)
  responsible_id  uuid references profiles(id),       -- aramayı yapacak (dağıtılabilir)
  called_at       timestamptz,
  status          satisfaction_status not null default 'bekliyor',
  note            text,
  created_at      timestamptz not null default now()
);
create index on satisfaction_calls (company_id, responsible_id, status);

