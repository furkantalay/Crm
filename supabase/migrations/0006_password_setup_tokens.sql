-- Tek kullanımlık "şifre belirle" bağlantıları. Jetonun kendisi saklanmaz, sadece SHA-256 özeti.
create table password_setup_tokens (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users(id) on delete cascade,
  token_hash  text not null unique,
  created_by  uuid references auth.users(id),
  expires_at  timestamptz not null,
  used_at     timestamptz,
  created_at  timestamptz not null default now()
);
alter table password_setup_tokens enable row level security;  -- politika yok: yalnız servis anahtarı erişir

-- Admin/yönetici, kendi şirketindeki bir kullanıcı için bağlantı oluşturur. Ham jetonu bir kez döndürür.
create or replace function create_password_setup_token(target_user uuid, valid_hours int default 24)
returns text
language plpgsql security definer set search_path = public, extensions as $$
declare
  raw text;
begin
  if current_user_role() not in ('admin', 'yonetici') then
    raise exception 'Yetkiniz yok.';
  end if;
  if not exists (select 1 from profiles where id = target_user and company_id = current_company_id()) then
    raise exception 'Kullanıcı bulunamadı.';
  end if;
  raw := encode(gen_random_bytes(24), 'hex');
  insert into password_setup_tokens (user_id, token_hash, created_by, expires_at)
  values (target_user, encode(digest(raw, 'sha256'), 'hex'), auth.uid(), now() + make_interval(hours => least(valid_hours, 72)));
  return raw;
end $$;
revoke execute on function create_password_setup_token(uuid, int) from public, anon;
grant execute on function create_password_setup_token(uuid, int) to authenticated;
